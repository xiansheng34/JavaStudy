package LC;

public class Demo3 {
    public static void main(String[] args) {
        int i=10;           //十进制
        int i1=010;         //八进制0
        int i2=0x10;        //十六进制0x
        System.out.println(i);
        System.out.println(i1);
        System.out.println(i2);
        System.out.println("=====================");
        //浮点数拓展
        //字符拓展
        char ch='a';
        char ch1='郭';
        System.out.println((int)ch);
        System.out.println((int)ch1);
        //转义符
        //Boolean拓展
    }
}
